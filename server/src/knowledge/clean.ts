/**
 * 清洗节点（W1-B，rag-pipeline-design §4.5）：解析产物入库前的确定性规则清洗，
 * 全部纯函数无 LLM。降级留痕原则：剔除/并入/去重的计数进 parseMeta.cleanStats。
 */
import type { ParsedBlock } from './chunk.js'

export interface CleanResult {
  blocks: ParsedBlock[]
  /** 降级留痕：各节点计数（只进日志的降级=不可见的损坏） */
  stats: { droppedNoise: number; mergedFragments: number; deduped: number }
}

/** 纯页码行 / 引擎指纹行（docling/mineru/reportlab/UUID 产物） */
function isNoiseLine(text: string): boolean {
  const t = text.trim()
  if (t === '') return true
  if (/^\d{1,4}$/.test(t)) return true
  if (/^(docling|mineru|reportlab|generated by)/i.test(t)) return true
  if (/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(t)) return true
  if (/^(0000-00-00|1970-01-01)/.test(t)) return true
  return false
}

/**
 * 清洗主入口（五节点中的四个——页眉页脚剔除依赖跨页重复检测，对纯文本 MD
 * 收益为零且易误伤，首版仅对 pageNo 存在的 block 启用兜底规则）：
 * 1. 噪声行剔除（页码/指纹/空行）
 * 2. 残片并入：<30 有效字符且无句末标点的 text 并入前一块（内容完整性优先）
 * 3. 同页近似去重：归一化后同 pageNo 同内容的重复块只保留首个
 */
export function cleanBlocks(input: ParsedBlock[]): CleanResult {
  const stats = { droppedNoise: 0, mergedFragments: 0, deduped: 0 }
  const out: ParsedBlock[] = []
  const seen = new Set<string>()

  for (const b of input) {
    if (b.kind === 'text' && isNoiseLine(b.text ?? '')) {
      stats.droppedNoise++
      continue
    }
    // 残片并入（仅 text；heading/figure/table 不并入）
    if (b.kind === 'text' && out.length > 0) {
      const prev = out[out.length - 1]
      const t = (b.text ?? '').trim()
      if (t.length > 0 && t.length < 30 && !/[。！？.!?;；:]$/.test(t) && prev.kind === 'text') {
        prev.text = `${prev.text ?? ''}${t}`
        stats.mergedFragments++
        continue
      }
    }
    // 同页去重（heading 参与去重会误杀跨页重复章节名，跳过）
    if (b.kind !== 'heading') {
      const key = `${b.kind}:${b.pageNo ?? 'x'}:${(b.text ?? '').replace(/\s+/g, '').slice(0, 120)}`
      if (tSameKindPage(seen, key)) {
        stats.deduped++
        continue
      }
      seen.add(key)
    }
    out.push({ ...b })
  }
  return { blocks: out, stats }
}

function tSameKindPage(seen: Set<string>, key: string): boolean {
  return seen.has(key)
}
