import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { publications, pagePaths, sources, type Publication } from '../lib/publications'
import { validateCidrs } from '../lib/locale'

export async function checkContent(items: Publication[] = publications) {
  const root = fileURLToPath(new URL('../', import.meta.url))
  const ids = new Set<string>(), paths = new Set<string>(), bodies = new Set<string>()
  for (const item of items) {
    if (!item.id || ids.has(item.id) || paths.has(item.path) || !/^[a-z0-9-]+(?:\/[a-z0-9-]+)?$/.test(item.path)) throw new Error('Duplicate/invalid content identity')
    ids.add(item.id); paths.add(item.path)
    if (!['guide', 'demo', 'page'].includes(item.kind) || ['demo', 'guides', 'contact'].includes(item.path) || (item.kind === 'guide' && !item.path.startsWith('guides/')) || (item.kind === 'demo' && !item.path.startsWith('demo/'))) throw new Error(`Invalid public content path/kind: ${item.id}`)
    if (!['published', 'draft'].includes(item.status)) throw new Error(`Invalid publication status: ${item.id}`)
    for (const locale of ['en', 'zh'] as const) {
      const t = item.translations[locale], other = locale === 'en' ? 'zh' : 'en'
      if (!t || t.locale !== locale || t.url !== `/${locale}/${item.path}` || t.translation !== item.translations[other]?.url) throw new Error(`Broken translation pair: ${item.id}`)
      if (!t.title || !t.summary || t.author !== 'project-maintainers' || t.reviewScope !== 'source-and-implementation-check') throw new Error(`Missing editorial metadata: ${item.id}`)
      for (const date of [t.modifiedAt, t.reviewedAt]) if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || !Number.isFinite(Date.parse(date)) || new Date(date).toISOString().slice(0, 10) !== date || date > new Date().toISOString().slice(0, 10)) throw new Error(`Invalid content date: ${item.id}`)
      if (t.reviewedAt < t.modifiedAt) throw new Error(`Content modified since last source check: ${item.id}`)
      if (!t.sources.length || t.sources.some(id => !Object.hasOwn(sources, id))) throw new Error(`Missing primary sources: ${item.id}`)
      if (!t.body.startsWith(`content/${locale}/`) || t.body.includes('..') || bodies.has(t.body)) throw new Error('Invalid MDX body location')
      bodies.add(t.body)
      const body = await readFile(resolve(root, t.body), 'utf8')
      const headings = [...body.matchAll(/^## (.+)$/gm)].map(m => m[1])
      if (body.length < (locale === 'zh' ? 200 : 500) || headings.length < 4 || JSON.stringify(headings) !== JSON.stringify(t.toc.map(h => h.title)) || t.toc.some((h, i) => h.id !== `section-${i + 1}`)) throw new Error(`Incomplete article or TOC: ${t.body}`)
      // No runtime imports, script or third-party embeds in editorial content.
      if (/^(?:import|export)\s|<script|<iframe|https?:\/\/[^\s)]*\?[^\s)]*(?:question|token)=/im.test(body)) throw new Error(`Unsafe MDX content: ${t.body}`)
    }
    if (!items.some(p => p.status === 'published' && p.kind === 'demo' && p.path === `demo/${item.relatedDemo}`)) throw new Error(`Missing related demo: ${item.id}`)
  }
  validateCidrs(await readFile(resolve(root, 'data/cn-ipv4.txt'), 'utf8'))
  return { articles: items.filter(i => i.status === 'published').length, pages: pagePaths.length * 2 }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await checkContent()
  const loaders = publications.filter(p => p.status === 'published').flatMap(p => (['en', 'zh'] as const).map(locale => `  ${JSON.stringify(`${p.id}:${locale}`)}: () => import(${JSON.stringify('@/' + p.translations[locale].body)}),`))
  await writeFile(new URL('../lib/publication-bodies.ts', import.meta.url), '// Generated by check-content.ts. Trusted, published repository MDX only.\nexport const publicationBodies = {\n' + loaders.join('\n') + '\n} as const\n')
  // The logger only recognizes build-approved public paths, never arbitrary URL segments.
  await writeFile(new URL('../runtime/public-paths.json', import.meta.url), JSON.stringify(['/', '/robots.txt', '/sitemap.xml', ...['en', 'zh'].flatMap(locale => pagePaths.map(path => `/${locale}${path ? `/${path}` : ''}`))], null, 2) + '\n')
  console.log(`Content checked: ${result.articles} bilingual publications, ${result.pages} public pages; CIDR snapshot valid.`)
}
