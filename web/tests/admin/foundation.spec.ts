import { test, expect } from './fixtures'
test('all ten menu links use one basename and preserve active route after refresh', async ({ page }) => {
  await page.goto('/admin/')
  const paths = ['/admin/membership', '/admin', '/admin/panel', '/admin/ai', '/admin/knowledge', '/admin/agents', '/admin/prompts', '/admin/evals', '/admin/queues', '/admin/observability']
  const navigation = page.getByRole('navigation', { name: '管理导航' })
  await expect(navigation.locator('a')).toHaveCount(10)
  for (let index = 0; index < paths.length; index++) {
    const link = navigation.locator('a').nth(index)
    await expect(link).toHaveAttribute('href', paths[index])
    await link.click()
    await expect(page).toHaveURL(new RegExp(paths[index].replace(/\/$/, '') + '/?$'))
    await expect(navigation.locator('.ant-menu-item-selected a')).toHaveAttribute('href', paths[index])
  }
  await page.reload()
  await expect(navigation.locator('.ant-menu-item-selected a')).toHaveAttribute('href', '/admin/observability')
})
test('login preserves deep link and errors, logout revokes and permits login again', async ({ page, apiFixture }) => {
  apiFixture.setAuthenticated(false)
  await page.goto('/admin/knowledge?view=documents')
  await page.getByLabel('账号', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('wrong')
  await page.getByRole('button', { name: '登录管理后台', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Invalid credentials')
  await page.getByLabel('密码', { exact: true }).fill('correct')
  await page.getByRole('button', { name: '登录管理后台', exact: true }).click()
  await expect(page.getByRole('heading', { name: '知识库', exact: true })).toBeVisible()
  await expect(page).toHaveURL(/\/admin\/knowledge\?view=documents/)
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page.getByLabel('账号', { exact: true })).toBeVisible()
  expect(apiFixture.requests.filter(request => request.path === '/api/auth/logout')).toHaveLength(1)
  await page.reload()
  await expect(page.getByLabel('账号', { exact: true })).toBeVisible()
})
test('AI settings have independent context, unsaved protection and component locale', async ({ page }) => {
  await page.goto('/admin/')
  await page.getByRole('button', { name: 'AI 配置', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'AI 配置', exact: true })
  await expect(drawer.getByLabel('Base URL', { exact: true })).toHaveValue('https://example.invalid/v1')
  await drawer.getByLabel('Base URL', { exact: true }).fill('https://changed.invalid')
  await drawer.getByRole('button', { name: /close|关闭/i }).click()
  await expect(page.locator('.ant-modal-confirm-title').filter({ hasText: '放弃未保存的修改？' })).toBeVisible()
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await expect(drawer).toBeVisible()
})
