/**
 * Regenerate the Traditional Chinese (zh-TW) UI dictionary and the runtime
 * simplified→traditional converter for the terminal (web app) from the
 * simplified source in locales/zh-CN/.
 *
 * Derived artifacts, committed for reviewability:
 *   locales/zh-TW/*.json  — full dictionary, OpenCC s2twp (Taiwan phrasing)
 *   src/zh-tw.ts          — divergence snapshot used by toTraditional() for
 *                           runtime strings that do not live in the dictionary
 *                           (e.g. Brooks bilingual term data)
 *
 * Run after editing any locales/zh-CN/*.json:
 *   pnpm --filter @biance/shared-ui sync:zh-tw
 *
 * The website keeps its own derived tree (content/zh-TW) with the same
 * conversion profile; the two generators intentionally share the OpenCC
 * settings (cn→twp, 賬→帳) so the properties stay consistent.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import OpenCC from 'opencc-js'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const phraseConverter = OpenCC.Converter({ from: 'cn', to: 'twp' })
const charConverter = OpenCC.Converter({ from: 'cn', to: 't' })

/** TW convention prefers 帳號; OpenCC emits 賬號. */
export const toTw = (value: string) => phraseConverter(value).replace(/賬/g, '帳')

/** JSON value walker: convert every string leaf, keep structure and keys. */
function convertJson(value: unknown): unknown {
  if (typeof value === 'string') return toTw(value.replace(/(?<=[\u3400-\u9fff])\s+(?=[\u3400-\u9fff])/g, ''))
  if (Array.isArray(value)) return value.map(convertJson)
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, convertJson(v)]))
  }
  return value
}

async function syncDictionaries() {
  const dir = join(root, 'src/locales/zh-CN')
  const target = join(root, 'src/locales/zh-TW')
  const files = (await readdir(dir)).filter(name => name.endsWith('.json'))
  for (const name of files) {
    const source = JSON.parse(await readFile(join(dir, name), 'utf8'))
    await writeFile(join(target, name), JSON.stringify(convertJson(source), null, 2) + '\n')
  }
  return files.length
}

async function syncConverter() {
  const chars: Record<string, string> = {}
  for (let cp = 0x3400; cp <= 0x9fff; cp++) {
    const ch = String.fromCodePoint(cp)
    const converted = charConverter(ch)
    if (converted !== ch) chars[ch] = converted
  }
  const lines = [
    '/**',
    ' * Character/phrase-level simplified→traditional fallback for runtime strings that',
    ' * live OUTSIDE the i18n dictionaries (bilingual Brooks term data, admin-configured',
    ' * labels). Generated by scripts/sync-zh-tw.ts — do not edit by hand; unknown',
    ' * characters pass through unchanged.',
    ' */',
    'const CHARS: Record<string, string> = {',
  ]
  const keys = Object.keys(chars)
  for (let i = 0; i < keys.length; i += 8) {
    lines.push('  ' + keys.slice(i, i + 8).map(key => `${JSON.stringify(key)}: ${JSON.stringify(chars[key])}`).join(', ') + ',')
  }
  lines.push('}')
  lines.push("export function toTraditional(value: string): string {")
  lines.push("  return [...value].map(ch => CHARS[ch] ?? ch).join('')")
  lines.push('}')
  await writeFile(join(root, 'src/zh-tw.ts'), lines.join('\n') + '\n')
  return keys.length
}

const dictionaries = await syncDictionaries()
const chars = await syncConverter()
console.log(`zh-TW synced: ${dictionaries} dictionary files, converter ${chars} chars`)
